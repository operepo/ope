#!/bin/bash
# Build-time helper: install one intermediate canvas release into /opt/canvas-upgrade/step<N>
# Only what db:migrate needs - ruby code + production gems (no node, no compiled assets, no specs).
#
# usage: build_step.sh <step> <canvas_release> <ruby_series> <canvas_rails> <bundler_version>
set -euxo pipefail

STEP=$1
CANVAS_RELEASE=$2
RUBY_SERIES=$3
RAILS_SERIES=$4
BUNDLER_VER=$5

D=/opt/canvas-upgrade/step$STEP
mkdir -p "$D"
cd "$D"

# --- canvas source for this release
git init -q
git remote add origin https://github.com/instructure/canvas-lms
git fetch -q --no-tags --depth 1 origin "refs/tags/${CANVAS_RELEASE}:refs/tags/${CANVAS_RELEASE}"
git checkout -q "${CANVAS_RELEASE}"
# Not needed to run migrations - keeps the image smaller
rm -rf .git spec doc ui packages node_modules public/dist

# Dummy configs (database.yml / security.yml / domain.yml / delayed_jobs.yml are generated by upgrade.sh).
# redis.yml / cache_store.yml are left out on purpose - the upgrade runs without redis (canvas falls back
# to a local cache) and the final ope-canvas startup flushes redis anyway.
for f in amazon_s3 database delayed_jobs domain file_store outgoing_mail security external_migration dynamic_settings; do
    if [ -f "config/$f.yml.example" ]; then cp "config/$f.yml.example" "config/$f.yml"; fi
done

# --- gems for this release, with the ruby it was built for
export GEM_HOME=$D/.gems
export PATH=$GEM_HOME/bin:$PATH
export CANVAS_RAILS=$RAILS_SERIES
# Only use the lockfile for this step's rails version - otherwise bundler-multilock re-resolves the other
# rails variants' lockfiles too, which breaks on test-only gems that have newer releases since (pact-mock_service)
export BUNDLE_LOCKFILE=Gemfile.lock   # this step's rails version uses the main Gemfile.lock (verified per step)
"gem$RUBY_SERIES" install bundler --no-document -v "$BUNDLER_VER"
head -1 "$GEM_HOME/bin/bundle"   # shebang shows which ruby runs this step
bundle config set --local build.nokogiri --use-system-libraries
bundle config set --local build.ffi --enable-system-libffi
bundle config set --local without "development test"
bundle install --jobs "$(nproc)"
rm -rf "$GEM_HOME/cache"

# --- OPE patches (same as ope-canvas start.sh) - must be in place before any migration runs
# OPE ids are school_range * 1e9 (> switchman's default 10 trillion per shard) - without this switchman
# would treat OPE ids as global ids on another shard.
patched=0
for f in $(grep -rl "10_000_000_000_000" "$GEM_HOME"/gems/switchman-*/lib "$GEM_HOME"/gems/switchman-*/app 2>/dev/null || true); do
    sed -i -- "s/10_000_000_000_000/1_000_000_000_000_000/g" "$f"
    patched=1
done
if [ "$patched" != "1" ]; then echo "ERROR - switchman shard id range not found/patched"; exit 1; fi

patch_if_exists() {  # file sed-expression
    if [ -f "$1" ]; then sed -i -- "$2" "$1"; else echo "  (skip - $1 not found)"; fi
}
# Version table partitions - essentially off for OPE's large ids
patch_if_exists config/initializers/simply_versioned.rb "s/5_000_000/1_000_000_000_000_000/g"
# Older canvas bugs that OPE patches (no-ops on releases where the files are gone)
patch_if_exists app/models/assignment.rb "s/\:\:int4\[\]/\:\:int8\[\]/g"
patch_if_exists db/migrate/20200211143240_split_up_user_preferences.rb "s/n_strand => \[\"user_preference_migration\"/n_strand\: \[\"user_preference_migration\"/g"
patch_if_exists lib/data_fixup/change_immersive_reader_allowed_on_to_on.rb "s/Account.root_accounts.active.where.not(id: Account.site_admin.id)/# Account.root_accounts.active.where.not(id: Account.site_admin.id)/g"

# Brand regeneration migrations (version = hash of the default brand variables, so a new one shows up whenever
# the defaults change) re-render every brand's css and need compiled assets ("you must run gulp rev first"),
# which these steps don't have. Skip them here - ope-canvas runs its own (newest) one plus
# brand_configs:generate_and_upload_all at startup with real compiled assets.
for f in db/migrate/*_regenerate_brand_files_based_on_new_defaults_*.rb; do
    [ -f "$f" ] || continue
    cls=$(grep -oE '^class [A-Za-z0-9_]+' "$f" | head -1 | cut -d' ' -f2)
    printf '\n# OPE upgrade step: brand files are regenerated by ope-canvas at startup\n%s.class_eval { def up; say "OPE: skipped (brand files are regenerated by ope-canvas)"; end }\n' "$cls" >> "$f"
done

# OPE upgrade helper tasks (sequence range / null root_account_id fixes)
cp /opt/ope/ope_upgrade.rake lib/tasks/ope_upgrade.rake

echo "${CANVAS_RELEASE}|${RUBY_SERIES}|${RAILS_SERIES}" > "$D/STEP_INFO"
du -sh "$D"
